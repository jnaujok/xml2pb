"""Tests for .proto generation from an XSD."""

from __future__ import annotations

import re
from types import SimpleNamespace
from typing import Any

import pytest

from xml2pb import ConversionError, ProtoGenerator, convert, generate_proto, load_proto
from xml2pb.generator import builtin_name, declared_attributes, enum_values


def body(text: str, message: str) -> list[str]:
    """Field lines of ``message`` in generated proto ``text``."""
    m = re.search(rf"^message {message} {{\n(.*?)^}}", text, re.M | re.S)
    assert m, f"message {message} not in:\n{text}"
    return [ln.strip() for ln in m.group(1).splitlines()]


def enum_body(text: str, name: str) -> list[str]:
    m = re.search(rf"^enum {name} {{\n(.*?)^}}", text, re.M | re.S)
    assert m, f"enum {name} not in:\n{text}"
    return [ln.strip() for ln in m.group(1).splitlines()]


@pytest.fixture(scope="module")
def order_proto(orders_xsd) -> str:
    return generate_proto(orders_xsd, ["order"], package="acme.gen")


class TestOrderFixture:
    def test_header(self, order_proto):
        assert order_proto.startswith("// Generated by xml2pb from orders.xsd\n")
        assert "// Top-level elements: order\n" in order_proto
        assert 'syntax = "proto3";' in order_proto
        assert "package acme.gen;" in order_proto
        assert 'import "google/protobuf/timestamp.proto";' in order_proto

    def test_order_fields(self, order_proto):
        assert body(order_proto, "Order") == [
            "optional int32 version = 1;  // attribute, xs:int",
            "optional int64 order_id = 2;  // xs:long",
            "optional Status status = 3;",
            "google.protobuf.Timestamp placed_at = 4;  // xs:dateTime",
            "optional bool paid = 5;",
            "optional double total = 6;  // xs:decimal",
            "repeated Line line = 7;",
            "optional string tags = 8;  // xs:list (space-separated)",
            "optional bytes checksum = 9;  // xs:hexBinary",
            "optional bytes blob = 10;  // xs:base64Binary",
            "optional float weight = 11;",
            "optional string ship = 12;  // xs:date",
            "optional double discount = 13;",
            "Customer customer = 14;",
            "repeated Entry meta = 15;",
            "Refs refs = 16;",
            "optional string note = 17;",
        ]

    def test_named_and_anonymous_types(self, order_proto):
        assert body(order_proto, "Money") == [
            "optional string currency = 1;  // attribute",
            "optional double value = 2;  // element text, xs:decimal",
        ]
        assert body(order_proto, "Customer")[0] == "optional string id = 1;  // attribute"
        assert body(order_proto, "Refs") == ["repeated string ref = 1;"]  # via repeating group

    def test_enum(self, order_proto):
        assert enum_body(order_proto, "Status") == [
            "STATUS_UNSPECIFIED = 0;",
            "STATUS_NEW = 1;",
            "STATUS_IN_PROGRESS = 2;",
            "STATUS_DONE = 3;",
        ]

    def test_compiles(self, order_proto, tmp_path):
        p = tmp_path / "gen.proto"
        p.write_text(order_proto)
        pool, fd, _ = load_proto(p)
        assert fd.package == "acme.gen"

    def test_round_trip_converts_without_gaps(self, order_proto, orders_xsd, order_xml, tmp_path):
        p = tmp_path / "gen.proto"
        p.write_text(order_proto)
        r = convert(orders_xsd, p, order_xml)
        m: Any = r.message
        assert r.skipped == [] and r.subset_issues == []
        assert m.order_id == 42 and m.status == 2 and m.tags == "1 2 3"
        assert m.total == 19.95 and m.line[1].price.currency == "EUR"
        assert not m.HasField("discount")  # xsi:nil -> unset optional scalar
        assert [(e.key, e.value) for e in m.meta] == [("channel", "web"), ("region", "eu")]
        assert m.customer.email == "ada@example.com" and m.note == "leave at door"


class TestOptions:
    def test_no_package(self, orders_xsd):
        assert "package" not in generate_proto(orders_xsd, ["ping"])

    def test_decimal_string(self, orders_xsd):
        text = generate_proto(orders_xsd, ["order"], decimal="string")
        assert "optional string total = 6;  // xs:decimal" in body(text, "Order")

    def test_datetime_string(self, orders_xsd):
        text = generate_proto(orders_xsd, ["order"], datetime_mode="string")
        assert "optional string placed_at = 4;  // xs:dateTime" in body(text, "Order")
        assert "timestamp.proto" not in text

    def test_no_optional(self, orders_xsd):
        text = generate_proto(orders_xsd, ["order"], use_optional=False)
        assert "int64 order_id = 2;  // xs:long" in body(text, "Order")
        assert "optional" not in text

    @pytest.mark.parametrize("kw", [{"decimal": "float"}, {"datetime_mode": "epoch"}])
    def test_invalid_modes(self, orders_xsd, kw):
        with pytest.raises(ConversionError, match="must be one of"):
            generate_proto(orders_xsd, ["order"], **kw)


class TestElementSelection:
    def test_simple_type_root(self, orders_xsd):
        text = generate_proto(orders_xsd, ["ping"])
        assert body(text, "Ping") == ["optional string value = 1;"]

    def test_multiple_and_duplicates(self, orders_xsd):
        text = generate_proto(orders_xsd, ["ping", "order", "ping"])
        assert "// Top-level elements: ping, order" in text
        assert text.index("message Ping") < text.index("message Order")

    def test_case_insensitive_lookup(self, orders_xsd):
        assert "message Order {" in generate_proto(orders_xsd, ["ORDER"])

    def test_qualified_name(self, orders_xsd):
        assert "message Order {" in generate_proto(orders_xsd, ["{urn:acme:orders}order"])

    def test_not_found(self, orders_xsd):
        with pytest.raises(
            ConversionError, match=r"'invoice' not found in XSD. Available: order, ping"
        ):
            generate_proto(orders_xsd, ["invoice"])

    def test_nothing_requested(self, orders_xsd):
        with pytest.raises(ConversionError, match="No elements given"):
            generate_proto(orders_xsd, [])

    def test_multiple_matches_warn(self):
        el = SimpleNamespace(name="{a}x", type=SimpleNamespace(name=None, base_type=None))
        schema = SimpleNamespace(elements={"{a}x": el, "{b}x": el})
        warnings: list[str] = []
        ProtoGenerator(schema, warn=warnings.append).build(["x"], "s.xsd")
        assert warnings == ["'x' matches 2 global elements; using the first"]


class TestShapes:
    def test_recursive_type(self, xsd):
        p = xsd(
            """
            <xs:complexType name="Node"><xs:sequence>
              <xs:element name="label" type="xs:string"/>
              <xs:element name="child" type="Node" minOccurs="0" maxOccurs="unbounded"/>
            </xs:sequence></xs:complexType>
            <xs:element name="tree" type="Node"/>
            """
        )
        text = generate_proto(p, ["tree"])
        assert body(text, "Tree") == ["optional string label = 1;", "repeated Tree child = 2;"]

    def test_anonymous_name_collisions(self, xsd):
        p = xsd(
            """
            <xs:element name="a"><xs:complexType><xs:sequence>
              <xs:element name="item"><xs:complexType><xs:sequence>
                <xs:element name="x" type="xs:int"/></xs:sequence></xs:complexType></xs:element>
            </xs:sequence></xs:complexType></xs:element>
            <xs:element name="b"><xs:complexType><xs:sequence>
              <xs:element name="item"><xs:complexType><xs:sequence>
                <xs:element name="y" type="xs:int"/></xs:sequence></xs:complexType></xs:element>
            </xs:sequence></xs:complexType></xs:element>
            <xs:element name="c"><xs:complexType><xs:sequence>
              <xs:element name="item"><xs:complexType><xs:sequence>
                <xs:element name="z" type="xs:int"/></xs:sequence></xs:complexType></xs:element>
            </xs:sequence></xs:complexType></xs:element>
            """
        )
        text = generate_proto(p, ["a", "b", "c"])
        assert body(text, "A") == ["Item item = 1;"]
        assert body(text, "B") == ["BItem item = 1;"]  # parent-prefixed fallback
        assert body(text, "C") == ["CItem item = 1;"]
        assert "message Item {" in text and "message BItem {" in text

    def test_numeric_suffix_when_both_names_taken(self, xsd):
        p = xsd(
            """
            <xs:element name="item"><xs:complexType/></xs:element>
            <xs:element name="aItem"><xs:complexType/></xs:element>
            <xs:element name="a"><xs:complexType><xs:sequence>
              <xs:element name="item"><xs:complexType><xs:sequence>
                <xs:element name="x" type="xs:int"/></xs:sequence></xs:complexType></xs:element>
            </xs:sequence></xs:complexType></xs:element>
            """
        )
        text = generate_proto(p, ["item", "aItem", "a"])
        assert "message Item {}" in text and "message AItem {}" in text
        assert body(text, "A") == ["Item2 item = 1;"]

    def test_repeated_merge_and_wildcard(self, xsd):
        p = xsd(
            """
            <xs:element name="r"><xs:complexType><xs:sequence>
              <xs:element name="x" type="xs:string"/>
              <xs:any minOccurs="0" namespace="##other" processContents="lax"/>
              <xs:choice>
                <xs:element name="y" type="xs:string"/>
                <xs:element name="z" type="xs:string"/>
              </xs:choice>
              <xs:element name="x2" type="xs:string" minOccurs="0" maxOccurs="2"/>
            </xs:sequence></xs:complexType></xs:element>
            """
        )
        text = generate_proto(p, ["r"])
        assert body(text, "R") == [
            "optional string x = 1;",
            "optional string y = 2;",
            "optional string z = 3;",
            "repeated string x2 = 4;",
        ]

    def test_same_element_twice_becomes_repeated(self, xsd):
        p = xsd(
            """
            <xs:element name="r"><xs:complexType><xs:sequence>
              <xs:element name="x" type="xs:string"/>
              <xs:element name="y" type="xs:string"/>
              <xs:element name="x" type="xs:string" maxOccurs="3"/>
            </xs:sequence></xs:complexType></xs:element>
            """
        )
        assert body(generate_proto(p, ["r"]), "R") == [
            "repeated string x = 1;",
            "optional string y = 2;",
        ]

    def test_field_collision_warns(self, xsd):
        p = xsd(
            """
            <xs:element name="r"><xs:complexType><xs:sequence>
              <xs:element name="orderId" type="xs:string"/>
              <xs:element name="order_id" type="xs:string"/>
            </xs:sequence></xs:complexType></xs:element>
            """
        )
        warnings: list[str] = []
        text = generate_proto(p, ["r"], warn=warnings.append)
        assert body(text, "R") == ["optional string order_id = 1;"]
        assert warnings == [
            "R: 'order_id' collides with another field after name normalisation; omitted"
        ]

    def test_default_warning_goes_to_stderr(self, xsd, capsys):
        p = xsd(
            """
            <xs:element name="r"><xs:complexType><xs:sequence>
              <xs:element name="aB" type="xs:string"/>
              <xs:element name="a_b" type="xs:string"/>
            </xs:sequence></xs:complexType></xs:element>
            """
        )
        generate_proto(p, ["r"])
        assert "warning: R: 'a_b' collides" in capsys.readouterr().err

    def test_text_field_name_avoids_attribute(self, xsd):
        p = xsd(
            """
            <xs:element name="r"><xs:complexType><xs:simpleContent>
              <xs:extension base="xs:int">
                <xs:attribute name="value" type="xs:string"/>
              </xs:extension>
            </xs:simpleContent></xs:complexType></xs:element>
            """
        )
        assert body(generate_proto(p, ["r"]), "R") == [
            "optional string value = 1;  // attribute",
            "optional int32 text = 2;  // element text, xs:int",
        ]

    def test_plain_text_complex_type_is_scalar(self, xsd):
        p = xsd(
            """
            <xs:complexType name="Code"><xs:simpleContent>
              <xs:extension base="xs:string"/>
            </xs:simpleContent></xs:complexType>
            <xs:element name="r"><xs:complexType><xs:sequence>
              <xs:element name="code" type="Code"/>
            </xs:sequence></xs:complexType></xs:element>
            """
        )
        text = generate_proto(p, ["r"])
        assert body(text, "R") == ["optional string code = 1;"]
        assert "message Code" not in text


class TestSimpleTypes:
    @pytest.fixture
    def gen_types(self, xsd):
        def _gen(*types: str, **kw) -> list[str]:
            els = "".join(f'<xs:element name="f{i}" type="{t}"/>' for i, t in enumerate(types))
            p = xsd(
                '<xs:element name="r"><xs:complexType><xs:sequence>'
                f"{els}</xs:sequence></xs:complexType></xs:element>"
            )
            return body(generate_proto(p, ["r"], use_optional=False, **kw), "R")

        return _gen

    @pytest.mark.parametrize(
        "xs, expected",
        [
            ("xs:int", "int32 f0 = 1;  // xs:int"),
            ("xs:short", "int32 f0 = 1;  // xs:short"),
            ("xs:byte", "int32 f0 = 1;  // xs:byte"),
            ("xs:long", "int64 f0 = 1;  // xs:long"),
            ("xs:integer", "int64 f0 = 1;  // xs:integer"),
            ("xs:negativeInteger", "int64 f0 = 1;  // xs:negativeInteger"),
            ("xs:unsignedShort", "uint32 f0 = 1;  // xs:unsignedShort"),
            ("xs:unsignedLong", "uint64 f0 = 1;  // xs:unsignedLong"),
            ("xs:positiveInteger", "uint64 f0 = 1;  // xs:positiveInteger"),
            ("xs:boolean", "bool f0 = 1;"),
            ("xs:float", "float f0 = 1;"),
            ("xs:double", "double f0 = 1;"),
            ("xs:string", "string f0 = 1;"),
            ("xs:token", "string f0 = 1;  // xs:token"),
            ("xs:date", "string f0 = 1;  // xs:date"),
            ("xs:duration", "string f0 = 1;  // xs:duration"),
            ("xs:anyURI", "string f0 = 1;  // xs:anyURI"),
        ],
    )
    def test_builtins(self, gen_types, xs, expected):
        assert gen_types(xs) == [expected]

    def test_xsd11_datetimestamp(self, xsd):
        import xmlschema

        p = xsd(
            '<xs:element name="r"><xs:complexType><xs:sequence>'
            '<xs:element name="t" type="xs:dateTimeStamp"/>'
            "</xs:sequence></xs:complexType></xs:element>"
        )
        gen = ProtoGenerator(xmlschema.XMLSchema11(str(p)))
        assert body(gen.build(["r"], "s.xsd"), "R") == [
            "google.protobuf.Timestamp t = 1;  // xs:dateTimeStamp"
        ]

    def test_restriction_uses_base_builtin(self, xsd):
        p = xsd(
            """
            <xs:simpleType name="Pct"><xs:restriction base="xs:int">
              <xs:maxInclusive value="100"/></xs:restriction></xs:simpleType>
            <xs:simpleType name="Small"><xs:restriction base="Pct"/></xs:simpleType>
            <xs:element name="r"><xs:complexType><xs:sequence>
              <xs:element name="p" type="Small"/>
            </xs:sequence></xs:complexType></xs:element>
            """
        )
        assert body(generate_proto(p, ["r"]), "R") == ["optional int32 p = 1;  // xs:int"]

    def test_union_and_untyped(self, xsd):
        p = xsd(
            """
            <xs:simpleType name="U"><xs:union memberTypes="xs:int xs:date"/></xs:simpleType>
            <xs:element name="r"><xs:complexType><xs:sequence>
              <xs:element name="u" type="U"/>
              <xs:element name="anything"/>
            </xs:sequence></xs:complexType></xs:element>
            """
        )
        lines = body(generate_proto(p, ["r"]), "R")
        assert lines[0] == "optional string u = 1;  // xs:union"
        assert lines[1] == "AnyType anything = 2;"  # xs:anyType: an (empty) message

    def test_enum_naming_and_dedup(self, xsd):
        p = xsd(
            """
            <xs:element name="r"><xs:complexType><xs:sequence>
              <xs:element name="size"><xs:simpleType><xs:restriction base="xs:string">
                <xs:enumeration value="x-small"/>
                <xs:enumeration value="X Small"/>
                <xs:enumeration value="---"/>
                <xs:enumeration value="large"/>
                <xs:enumeration value="large"/>
              </xs:restriction></xs:simpleType></xs:element>
              <xs:element name="n"><xs:simpleType><xs:restriction base="xs:int">
                <xs:enumeration value="1"/><xs:enumeration value="2"/>
              </xs:restriction></xs:simpleType></xs:element>
            </xs:sequence></xs:complexType></xs:element>
            """
        )
        text = generate_proto(p, ["r"])
        assert body(text, "R") == ["optional Size size = 1;", "optional int32 n = 2;  // xs:int"]
        assert enum_body(text, "Size") == [
            "SIZE_UNSPECIFIED = 0;",
            "SIZE_X_SMALL = 1;",
            "SIZE_X_SMALL_2 = 2;",  # collision after normalisation
            "SIZE_EMPTY = 3;",
            "SIZE_LARGE = 4;",
        ]

    def test_shared_enum_type_emitted_once(self, xsd):
        p = xsd(
            """
            <xs:simpleType name="YesNo"><xs:restriction base="xs:string">
              <xs:enumeration value="yes"/><xs:enumeration value="no"/>
            </xs:restriction></xs:simpleType>
            <xs:element name="r"><xs:complexType><xs:sequence>
              <xs:element name="a" type="YesNo"/><xs:element name="b" type="YesNo"/>
            </xs:sequence></xs:complexType>
            <xs:attribute name="c" type="YesNo"/></xs:element>
            """.replace("</xs:complexType>\n            <xs:attribute", "<xs:attribute").replace(
                '"YesNo"/></xs:element>', '"YesNo"/></xs:complexType></xs:element>'
            )
        )
        text = generate_proto(p, ["r"])
        assert text.count("enum YesNo {") == 1
        assert body(text, "R") == [
            "optional YesNo c = 1;  // attribute",
            "optional YesNo a = 2;",
            "optional YesNo b = 3;",
        ]

    def test_generated_enum_round_trip(self, xsd, write, tmp_path):
        p = xsd(
            """
            <xs:element name="r"><xs:complexType><xs:sequence>
              <xs:element name="state"><xs:simpleType><xs:restriction base="xs:string">
                <xs:enumeration value="on-hold"/><xs:enumeration value="shipped"/>
              </xs:restriction></xs:simpleType></xs:element>
            </xs:sequence></xs:complexType></xs:element>
            """
        )
        proto_path = tmp_path / "g.proto"
        proto_path.write_text(generate_proto(p, ["r"]))
        r = convert(p, proto_path, write("r.xml", "<r><state>on-hold</state></r>"))
        assert r.message.state == 1


class TestHelpers:
    def test_builtin_name_chain_and_none(self):
        xs = "{http://www.w3.org/2001/XMLSchema}"
        base = SimpleNamespace(name=xs + "int", base_type=None)
        mid = SimpleNamespace(name="{urn:x}Pct", base_type=base)
        assert builtin_name(SimpleNamespace(name=None, base_type=mid)) == "int"
        assert builtin_name(None) is None
        assert builtin_name(SimpleNamespace(name="{urn:x}Loop", base_type=None)) is None

    def test_builtin_name_gives_up_on_cycles(self):
        a = SimpleNamespace(name="{urn:x}A", base_type=None)
        a.base_type = a
        assert builtin_name(a) is None

    def test_enum_values_from_facets(self):
        xs = "{http://www.w3.org/2001/XMLSchema}"
        st = SimpleNamespace(
            facets={xs + "enumeration": SimpleNamespace(enumeration=["a", "b", "a"])}
        )
        assert enum_values(st) == ["a", "b"]
        assert enum_values(SimpleNamespace()) is None
        assert enum_values(SimpleNamespace(enumeration=[])) is None

    def test_declared_attributes_skips_wildcards_and_xsi(self):
        ctype = SimpleNamespace(
            attributes={
                "id": 1,
                None: 2,
                "{http://www.w3.org/2001/XMLSchema-instance}type": 3,
                "{urn:x}lang": 4,
            }
        )
        assert declared_attributes(ctype) == [("id", 1), ("lang", 4)]

    def test_simple_with_no_type(self):
        gen = ProtoGenerator(SimpleNamespace(elements={}))
        assert gen._simple(None, "x", None) == ("string", "scalar", None)  # type: ignore[arg-type]
